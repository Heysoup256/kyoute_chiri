from __future__ import annotations


def mk_item(
    item_id: str,
    label: str,
    detail: str,
    cloze: list[str],
    tags: list[str],
    imp: str = "A",
    freq: bool = True,
) -> dict:
    """KnowledgeItem レコードを組み立てる。"""
    return {
        "id": item_id,
        "label": label,
        "detail": detail,
        "clozeTerms": cloze,
        "tags": tags,
        "examMeta": {
            "isFrequent": freq,
            "importance": imp,
            "pastExamRefs": [],
        },
    }


def mk_city(
    cid: str,
    name_ja: str,
    name_en: str,
    lat: float,
    lng: float,
    elev: int,
    koppen: str,
    koppen_ja: str,
    factors: list[str],
    temp: list[float],
    precip: list[int],
    imp: str = "A",
) -> dict:
    """気候グラフ用の代表都市データを組み立てる。"""
    return {
        "cityId": cid,
        "nameJa": name_ja,
        "nameEn": name_en,
        "lat": lat,
        "lng": lng,
        "elevationM": elev,
        "koppenCode": koppen,
        "koppenNameJa": koppen_ja,
        "factors": factors,
        "monthlyTempC": temp,
        "monthlyPrecipMm": precip,
        "dataSource": "WMO / NOAA 1991-2020目安",
        "examMeta": {
            "isFrequent": imp in ("S", "A"),
            "importance": imp,
            "pastExamRefs": [],
        },
    }


