def main() -> None:
    extra_base: dict[str, dict] = {}
    overviews = json.loads(OVERVIEWS_PATH.read_text(encoding="utf-8"))
    top_cities = json.loads(TOP_CITIES_PATH.read_text(encoding="utf-8"))
    visuals = json.loads(VISUALS_PATH.read_text(encoding="utf-8")) if VISUALS_PATH.exists() else {}

    for c in COUNTRIES_26:
        iso = c["iso3"]
        extra_base[iso] = {
            "iso3": iso,
            "nameJa": c["nameJa"],
            "nameEn": c["nameEn"],
            "region": c["region"],
            "subRegion": c["subRegion"],
            "capital": c["capital"],
            "examSummary": {
                "manualRankOverride": c["rank"],
                "frequentTopics": c["topics"],
            },
            "nature": {
                "orogenicBelts": c["belts"],
                "summary": c["natureSummary"],
                "items": c["natureItems"],
            },
            "climate": {
                "koppenCodes": c["koppenCodes"],
                "summary": c["climateSummary"],
                "cities": [c["city"]],
            },
            "industry": {
                "whittleseyTypes": c["whittlesey"],
                "agriculture": c["agItems"],
                "resourcesAndEnergy": c["resItems"],
                "industrialRegions": c["indItems"],
                "trade": {
                    "majorExports": c["exports"],
                    "majorImports": c["imports"],
                    "majorPartners": c["partners"],
                },
            },
            "cultureAndHistory": {
                "languageFamily": c["langFamily"],
                "officialLanguages": c["langs"],
                "religions": c["religions"],
                "ethnicGroups": c["ethnic"],
                "regionalIntegrations": c["integrations"],
                "historicalContext": c["histItems"],
            },
        }

        overviews[iso] = {
            "quickOverview": {
                "headline": c["headline"],
                "summary": c["ovSummary"],
                "keyPoints": c["keyPoints"],
            },
            "dailyLife": {
                "summary": c["dlSummary"],
                "food": c["dlFood"],
                "housing": c["dlHousing"],
                "streetNote": c["dlStreet"],
                "wikiPhotoTargets": c["wikiTargets"],
            },
        }

        tc_obj: dict = {"topCities": c["topCities"]}
        if c.get("specialRegions"):
            tc_obj["specialRegions"] = c["specialRegions"]
        top_cities[iso] = tc_obj

        if c.get("visual"):
            visuals[iso] = [c["visual"]]

    EXTRA_BASE_OUT.write_text(json.dumps(extra_base, ensure_ascii=False, indent=2), encoding="utf-8")
    OVERVIEWS_PATH.write_text(json.dumps(overviews, ensure_ascii=False, indent=2), encoding="utf-8")
    TOP_CITIES_PATH.write_text(json.dumps(top_cities, ensure_ascii=False, indent=2), encoding="utf-8")
    VISUALS_PATH.write_text(json.dumps(visuals, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(extra_base)} detailed countries to {EXTRA_BASE_OUT.name}; updated overviews({len(overviews)}), topCities({len(top_cities)}), visuals({len(visuals)})")


if __name__ == "__main__":
    main()
