    return {
        "cityId": cid,
        "nameJa": name_ja,
        "nameEn": name_en,
        "lat": lat,
        "lng": lng,
        "elevationM": elev,
        "koppenCode": koppen,
        "koppenNameJa": k_name,
        "factors": factors,
        "monthlyTempC": temps,
        "monthlyPrecipMm": precips,
        "dataSource": source,
        "examMeta": {"isFrequent": True, "importance": "A", "pastExamRefs": []},
    }


