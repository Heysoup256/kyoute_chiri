def upsert_by_id(existing: list[dict], new_items: list[dict]) -> list[dict]:
    new_map = {x["id"]: x for x in new_items}
    out = [new_map[x["id"]] if x["id"] in new_map else x for x in existing]
    seen = {x["id"] for x in existing}
    for x in new_items:
        if x["id"] not in seen:
            out.append(x)
            seen.add(x["id"])
    return out


