def mk_slider(
    sid: str,
    cat: str,
    title: str,
    subtitle: str,
    mode: str,
    unit: str,
    source: str,
    shift_summary: str,
    related: list[str],
    frames: list[dict],
) -> dict:
    return {
        "id": sid,
        "category": cat,
        "title": title,
        "subtitle": subtitle,
        "displayMode": mode,
        "unit": unit,
        "source": source,
        "shiftSummary": shift_summary,
        "relatedIso3s": related,
        "frames": frames,
    }


def fr(yr: str, note: str, items: list[tuple]) -> dict:
    out_items = []
    for row in items:
        lbl, val = row[0], row[1]
        iso = row[2] if len(row) > 2 else None
        col = row[3] if len(row) > 3 else None
        inote = row[4] if len(row) > 4 else None
        d: dict = {"label": lbl, "value": val}
        if iso:
            d["iso3"] = iso
        if col:
            d["color"] = col
        if inote:
            d["note"] = inote
        out_items.append(d)
    return {"yearLabel": yr, "periodNote": note, "items": out_items}


