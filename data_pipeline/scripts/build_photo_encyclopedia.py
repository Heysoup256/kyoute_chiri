def main() -> None:
    place_photos = (
        json.loads(PLACE_PHOTOS_PATH.read_text(encoding="utf-8"))
        if PLACE_PHOTOS_PATH.exists()
        else {}
    )
    life_photos = (
        json.loads(LIFE_PHOTOS_PATH.read_text(encoding="utf-8"))
        if LIFE_PHOTOS_PATH.exists()
        else {}
    )
    cache = (
        json.loads(CACHE_PATH.read_text(encoding="utf-8"))
        if CACHE_PATH.exists()
        else {}
    )

    wiki_needed = [row[5] for row in RAW_ENTRIES if row[5] and row[5] not in cache]
    if wiki_needed:
        print(f"Fetching {len(wiki_needed)} missing encyclopedia thumbnails from Wikipedia API...")
        fetched = query_wiki_thumbs(wiki_needed)
        cache.update(fetched)
        CACHE_PATH.write_text(json.dumps(cache, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Cached encyclopedia photos total={len(cache)}")

    entries: list[dict] = []
    wiki_hits = 0
    fallback_hits = 0
    for row in RAW_ENTRIES:
        eid, cat, title, loc, koppen, wiki_title, fb_spec, clues, summary, exam_pt, isos, lat, lng, zoom = row
        photo_url = ""
        photo_credit = ""

        if wiki_title and wiki_title in cache and is_usable_photo_url(cache[wiki_title].get("url")):
            photo_url = cache[wiki_title]["url"]
            photo_credit = cache[wiki_title]["credit"]
            wiki_hits += 1
        else:
            if fb_spec[0] == "place":
                ph = place_photos.get(fb_spec[1]) or {}
                photo_url = ph.get("url", "")
                photo_credit = ph.get("credit", "")
            elif fb_spec[0] == "life":
                arr = life_photos.get(fb_spec[1]) or []
                idx = fb_spec[2] if len(arr) > fb_spec[2] else 0
                if arr:
                    photo_url = arr[idx].get("url", "")
                    photo_credit = arr[idx].get("credit", "")
            fallback_hits += 1

        if not photo_url:
            raise ValueError(f"No usable photo found for encyclopedia entry {eid}!")

        entries.append(
            {
                "id": eid,
                "category": cat,
                "title": title,
                "locationLabel": loc,
                "koppenCodes": koppen,
                "photoUrl": photo_url,
                "photoCredit": photo_credit or "Wikimedia Commons",
                "visualClues": clues,
                "inferenceSummary": summary,
                "examPoint": exam_pt,
                "relatedIso3s": isos,
                "lat": lat,
                "lng": lng,
                "zoom": zoom,
            }
        )

    out_obj = {"schemaVersion": "1.0.0", "generatedAt": "2026-11-26", "entries": entries}
    txt = json.dumps(out_obj, ensure_ascii=False, indent=2) + "\n"
    if SUBCODE_RE.findall(txt):
        raise ValueError(f"Non-13 Koppen subcode in encyclopedia: {SUBCODE_RE.findall(txt)}")
    if HYPE_RE.findall(txt):
        raise ValueError(f"Hype wording in encyclopedia: {HYPE_RE.findall(txt)}")

    OUT_PATH.write_text(txt, encoding="utf-8")
    print(f"Wrote {OUT_PATH.name}: entries={len(entries)} (wiki_hits={wiki_hits}, fallback_hits={fallback_hits})")


if __name__ == "__main__":
    main()
