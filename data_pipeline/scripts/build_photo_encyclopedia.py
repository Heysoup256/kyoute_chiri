def is_usable_photo_url(url: str | None) -> bool:
    if not url or not url.startswith("https://"):
        return False
    low = url.lower().split("?")[0]
    if any(bad in low for bad in REJECT_SUBSTRS):
        return False
    return any(ext in low for ext in (".jpg", ".jpeg", ".webp"))


def query_wiki_thumbs(titles: list[str]) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    clean_titles = list(dict.fromkeys(t for t in titles if t))
    for i in range(0, len(clean_titles), 50):
        batch = clean_titles[i : i + 50]
        params = urllib.parse.urlencode(
            {
                "action": "query",
                "titles": "|".join(batch),
                "redirects": "1",
                "prop": "pageimages|info",
                "inprop": "url",
                "pithumbsize": "640",
                "format": "json",
            }
        )
        req = urllib.request.Request(
            f"{WIKI_API}?{params}",
            headers={"User-Agent": "kyoute-chiri-edu/1.0 (local study tool)"},
        )
        try:
            with urllib.request.urlopen(req, timeout=20) as resp:
                data = json.loads(resp.read().decode("utf-8"))
        except Exception as exc:
            print(f"Wikipedia batch fetch skipped ({exc}); using cached/local photos.")
            break
        q = data.get("query", {})
        norm_map = {n["from"]: n["to"] for n in q.get("normalized", [])}
        redir_map = {r["from"]: r["to"] for r in q.get("redirects", [])}
        pages_by_title = {
            p["title"]: p for p in q.get("pages", {}).values() if "title" in p
        }
        for orig in batch:
            cur = redir_map.get(norm_map.get(orig, orig), norm_map.get(orig, orig))
            pg = pages_by_title.get(cur)
            if not pg:
                continue
            thumb = (pg.get("thumbnail") or {}).get("source")
            if is_usable_photo_url(thumb):
                out[orig] = {
                    "url": thumb,
                    "credit": f"Wikimedia Commons / Wikipedia ({pg.get('title', orig)})",
                }
    return out


