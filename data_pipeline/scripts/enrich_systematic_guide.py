def main() -> None:
    raw = json.loads(RAW_PATH.read_text(encoding="utf-8"))
    old_topics = {t["id"]: t for t in raw.get("topics", [])}

    # sys_urban_models / sys_settlement_forms / sys_urban_hierarchy / sys_demographic_transition / sys_migration_refugees
    urban_ids = {
        "sys_settlement_forms",
        "sys_urban_models",
        "sys_urban_hierarchy",
        "sys_demographic_transition",
        "sys_migration_refugees",
    }
    climate_move_ids = {"sys_biogeography"}

    merged_topics = []
    seen = set()

    for old_id, t in old_topics.items():
        if old_id in urban_ids:
            t["categoryId"] = "urban_population"
        elif old_id in climate_move_ids:
            t["categoryId"] = "climate_soil_env"
        elif old_id == "sys_whittlesey":
            t["categoryId"] = "agriculture_primary"
        elif t["categoryId"] == "economy_regions":
            t["categoryId"] = "industry_economy"
        elif old_id in {"sys_housing_irrigation", "sys_religion_matrix", "sys_language_ethnicity"}:
            t["categoryId"] = "religion_culture"

        if old_id in UPGRADES:
            t = {**t, **UPGRADES[old_id]}
        merged_topics.append(t)
        seen.add(old_id)

    for nt in NEW_TOPICS:
        if nt["id"] not in seen:
            merged_topics.append(nt)
            seen.add(nt["id"])

    # カテゴリ順に美しく並べる
    cat_order = {c["id"]: i for i, c in enumerate(CATEGORIES)}
    merged_topics.sort(key=lambda x: cat_order.get(x["categoryId"], 99))

    out_obj = {
        "schemaVersion": "2.0.0",
        "generatedAt": "2026-11-23T09:10:00Z",
        "categories": CATEGORIES,
        "topics": merged_topics,
    }

    RAW_PATH.write_text(json.dumps(out_obj, ensure_ascii=False, indent=2), encoding="utf-8")
    counts = {c["id"]: sum(1 for x in merged_topics if x["categoryId"] == c["id"]) for c in CATEGORIES}
    print(f"Updated systematic_geography_v1.json: categories={len(CATEGORIES)}, topics={len(merged_topics)}")
    print("  Counts by category:", counts)


