/**
 * japan_geography_v1.json の実データ（charts と prefRankings）を
 * StatMatrixSpec 形式に変換して日本国内統計ドリルで使用できるようにする。
 */
export function extractJapanDomesticMatrices(
  japanData: JapanGeographyDataset | null | undefined,
): StatMatrixSpec[] {
  const result: StatMatrixSpec[] = [];
  const charts = japanData?.domesticStats?.charts ?? [];

  for (const ch of charts) {
    if (!ch.categories || ch.categories.length < 4 || !ch.series || ch.series.length < 2) {
      continue;
    }
    const colLabels = ch.series.map((s) => s.name);
    const rows = ch.categories.map((cat, idx) => ({
      countryName: cat,
      values: ch.series.map((s) => Number(s.values[idx] ?? 0)),
    }));

    result.push({
      id: `jp_chart_${ch.id}`,
      title: ch.title,
      unit: ch.unit || '%',
      sameUnitAcrossCols: true,
      colLabels,
      rows,
      examPoint: ch.examPoint ?? ch.subtitle ?? '日本の地域別統計の違いを因果関係で整理しよう。',
    });
  }

  return result;
}
